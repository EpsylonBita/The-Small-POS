import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const SERVICE_NAME = 'the-small-pos';
const SUPPORTED_KEYRING_VERSION = '3.6.3';

export function assertSupportedKeyringVersion(lockSource) {
  const version = lockSource.match(/\[\[package\]\]\s*name = "keyring"\s*version = "([^"]+)"/s)?.[1];
  if (version !== SUPPORTED_KEYRING_VERSION) {
    throw new Error(
      `Unsupported keyring version ${version ?? '(missing)'}; verify the Windows target contract before regenerating`,
    );
  }
}

export function parseManagedCredentialKeys(source) {
  const scalarConstants = new Map();
  const scalarPattern = /(?:pub(?:\([^)]*\))?\s+)?const\s+(\w+)\s*:\s*&str\s*=\s*"([^"]+)"\s*;/g;
  for (const match of source.matchAll(scalarPattern)) {
    scalarConstants.set(match[1], match[2]);
  }

  const arrayConstants = new Map();
  const arrayPattern = /(?:pub(?:\([^)]*\))?\s+)?const\s+(\w+)\s*:\s*\[&str;\s*\d+\]\s*=\s*\[([\s\S]*?)\]\s*;/g;
  for (const match of source.matchAll(arrayPattern)) {
    arrayConstants.set(
      match[1],
      Array.from(match[2].matchAll(/"([^"]+)"/g), (value) => value[1]),
    );
  }

  const allKeysMatch = source.match(/const\s+ALL_KEYS\s*:\s*&\[&str\]\s*=\s*&\[([\s\S]*?)\]\s*;/);
  if (!allKeysMatch) {
    throw new Error('storage.rs does not expose the canonical ALL_KEYS registry');
  }

  const keys = allKeysMatch[1]
    .replace(/\/\/.*$/gm, '')
    .split(',')
    .map((token) => token.trim())
    .filter(Boolean)
    .map((token) => {
      const indexed = token.match(/^(\w+)\[(\d+)\]$/);
      if (indexed) {
        const values = arrayConstants.get(indexed[1]);
        const value = values?.[Number(indexed[2])];
        if (!value) {
          throw new Error(`ALL_KEYS references unresolved array entry ${token}`);
        }
        return value;
      }

      const value = scalarConstants.get(token);
      if (!value) {
        throw new Error(`ALL_KEYS references unresolved scalar ${token}`);
      }
      return value;
    });

  const duplicateKeys = keys.filter((key, index) => keys.indexOf(key) !== index);
  if (duplicateKeys.length > 0) {
    throw new Error(`ALL_KEYS contains duplicate keys: ${[...new Set(duplicateKeys)].join(', ')}`);
  }
  for (const key of keys) {
    if (!/^[a-z0-9_]+$/.test(key)) {
      throw new Error(`Managed credential key is unsafe for cmdkey: ${key}`);
    }
  }

  return keys;
}

export function renderManagedCredentialInclude(keys) {
  const targets = keys.map((key) => `\"${key}.${SERVICE_NAME}\"`).join(' ');

  return [
    '; @generated by scripts/generate-managed-credential-targets.mjs',
    '; Source of truth: src-tauri/src/storage.rs::ALL_KEYS',
    '; Target contract pinned to keyring 3.6.3: <key>.the-small-pos.',
    '; The helper treats Win32 ERROR_NOT_FOUND (1168) as idempotent success.',
    '; Run the generator after adding, removing, or renaming a managed credential.',
    '',
    '!macro THE_SMALL_POS_DELETE_MANAGED_CREDENTIALS',
    '  InitPluginsDir',
    '  File /oname=$PLUGINSDIR\\delete-managed-credentials.ps1 "${MANAGED_CREDENTIAL_DELETE_HELPER}"',
    `  nsExec::ExecToLog '\"$SYSDIR\\WindowsPowerShell\\v1.0\\powershell.exe\" -NoProfile -NonInteractive -ExecutionPolicy Bypass -File \"$PLUGINSDIR\\delete-managed-credentials.ps1\" ${targets}'`,
    '  Pop $0',
    '  ${If} $0 <> 0',
    '    MessageBox MB_OK|MB_ICONEXCLAMATION "Some saved POS credentials could not be removed. See the uninstall log. / Δεν ήταν δυνατή η διαγραφή ορισμένων αποθηκευμένων διαπιστευτηρίων POS. Δείτε το αρχείο καταγραφής."',
    '    SetErrorLevel 1',
    '  ${EndIf}',
    '!macroend',
    '',
  ].join('\n');
}

export function renderCredentialDeleteHelper() {
  return `# @generated by scripts/generate-managed-credential-targets.mjs
param([Parameter(Mandatory=$true, Position=0, ValueFromRemainingArguments=$true)][string[]]$Targets)
$ErrorActionPreference = 'Stop'
$source = @'
using System;
using System.Runtime.InteropServices;
public static class TheSmallCredentialDelete {
  [DllImport("advapi32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
  public static extern bool CredDelete(string target, int type, int flags);
}
'@
try {
  Add-Type -TypeDefinition $source
  $failed = @()
  foreach ($target in $Targets) {
    if (-not [TheSmallCredentialDelete]::CredDelete($target, 1, 0)) {
      $errorCode = [Runtime.InteropServices.Marshal]::GetLastWin32Error()
      if ($errorCode -ne 1168) { $failed += $errorCode }
    }
  }
  if ($failed.Count -gt 0) {
    [Console]::Error.WriteLine("Managed credential deletion failed for one or more entries; Win32 codes: " + ($failed -join ', '))
    exit 1
  }
  exit 0
} catch {
  [Console]::Error.WriteLine("Managed credential deletion helper failed before completion.")
  exit 1
}
`;
}

export function generatedTextMatches(actual, expected) {
  const normalizeLineEndings = (value) => value.replace(/\r\n/g, '\n');
  return normalizeLineEndings(actual) === normalizeLineEndings(expected);
}

function run() {
  const packageRoot = process.cwd();
  const storagePath = path.resolve(packageRoot, 'src-tauri/src/storage.rs');
  const lockPath = path.resolve(packageRoot, 'src-tauri/Cargo.lock');
  const outputPath = path.resolve(
    packageRoot,
    'src-tauri/generated/managed-credential-targets.nsh',
  );
  const expected = renderManagedCredentialInclude(
    parseManagedCredentialKeys(fs.readFileSync(storagePath, 'utf8')),
  );
  assertSupportedKeyringVersion(fs.readFileSync(lockPath, 'utf8'));
  const helperPath = path.resolve(packageRoot, 'src-tauri/generated/delete-managed-credentials.ps1');
  const expectedHelper = renderCredentialDeleteHelper();

  if (process.argv.includes('--check')) {
    const actual = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
    const actualHelper = fs.existsSync(helperPath) ? fs.readFileSync(helperPath, 'utf8') : '';
    if (
      !generatedTextMatches(actual, expected)
      || !generatedTextMatches(actualHelper, expectedHelper)
    ) {
      process.stderr.write(
        'Managed credential NSIS include is stale. Run: node scripts/generate-managed-credential-targets.mjs\n',
      );
      process.exitCode = 1;
    }
    return;
  }

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, expected, 'utf8');
  fs.writeFileSync(helperPath, expectedHelper, 'utf8');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  run();
}
